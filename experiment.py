#!/usr/bin/env python3
"""Reproducible *synthetic acoustic* speech-to-action surrogate; NOT real ASR.

Features: 8 temporal slices x 8 Goertzel frequency bins, computed with integers.
Classifier: supervised nearest-centroid fitted to training split.
Independent rule check: per-slice dominant-frequency command signature.
Run: python experiment.py --seed 20261113 --train 20 --test 12
"""
import argparse
import json
import math
import os
from pathlib import Path
import random
import statistics
import struct
import time

FS = 16000
N = 256
FRAMES = 8
BINS = (4, 7, 10, 13, 16, 19, 22, 25)
COEFF_Q14 = tuple(round(2 * math.cos(2 * math.pi * k / N) * 16384) for k in BINS)
LENGTH = 5120
SLICE = LENGTH // FRAMES
START = (SLICE - N) // 2
NAMES = ('STOP', 'FORWARD', 'BACK', 'LEFT', 'RIGHT', 'LIGHT')
VI = ('dừng', 'tiến', 'lùi', 'trái', 'phải', 'bật đèn')
SIG = ((0, 0, 1, 1, 0, 0, 1, 1), (1, 2, 3, 4, 1, 2, 3, 4),
       (4, 3, 2, 1, 4, 3, 2, 1), (1, 3, 1, 3, 1, 3, 1, 3),
       (3, 1, 3, 1, 3, 1, 3, 1), (5, 6, 7, 5, 6, 7, 5, 6))
UNKNOWN = 6


def synth(label, seed, profile=0, noise=0.08):
    """Artificial tones with acoustic variation, not human speech/dialects."""
    r = random.Random(seed)
    if label == UNKNOWN:
        signature = [r.randrange(8) for _ in range(FRAMES)]
    else:
        signature = SIG[label]
    samples = []
    gain = r.uniform(0.55, 0.85)
    drift = (profile - 1) * 0.10 + r.uniform(-0.06, 0.06)
    for i in range(LENGTH):
        tslot = min(FRAMES - 1, i // SLICE)
        k = BINS[signature[tslot]] + drift
        t = i / FS
        # Envelope and harmonic are purposefully simple: synthetic surrogate.
        envelope = 0.86 + 0.12 * math.sin(2 * math.pi * (i % SLICE) / SLICE)
        signal = math.sin(2 * math.pi * (k * FS / N) * t)
        signal += 0.07 * math.sin(2 * math.pi * (k * FS / N) * 2 * t)
        signal = gain * envelope * signal + noise * r.gauss(0, 1)
        samples.append(max(-32768, min(32767, round(signal * 10500))))
    return samples


def features(pcm):
    if len(pcm) != LENGTH:
        raise ValueError(f'expect exactly {LENGTH} signed PCM samples')
    output = []
    for frame in range(FRAMES):
        start = frame * SLICE + START
        power = []
        for coeff in COEFF_Q14:
            s1, s2 = 0, 0
            for sample in pcm[start:start + N]:
                s = int(sample) + ((coeff * s1) >> 14) - s2
                s2, s1 = s1, s
            p = s1*s1 + s2*s2 - ((coeff * s1 * s2) >> 14)
            power.append(max(0, p))
        mx = max(power)
        output.extend([(p * 255) // mx if mx else 0 for p in power])
    return output


def fit(train):
    sums = [[0] * 64 for _ in NAMES]
    count = [0] * len(NAMES)
    for label, vec in train:
        count[label] += 1
        for j, x in enumerate(vec):
            sums[label][j] += x
    if not all(count):
        raise ValueError('missing a class')
    return [[(x + count[i]//2)//count[i] for x in row] for i, row in enumerate(sums)]


def classify(vec, centroids):
    d = [sum((a-b)*(a-b) for a, b in zip(vec, centroid)) for centroid in centroids]
    best = min(range(len(d)), key=lambda i: d[i])
    return best, d[best], sorted(d)[1] - d[best]


def verify(vec, label, min_matches=7):
    if label < 0 or label >= len(NAMES):
        return False
    signature = tuple(max(range(8), key=lambda k: vec[i*8+k]) for i in range(FRAMES))
    return sum(a == b for a, b in zip(signature, SIG[label])) >= min_matches


def gate(pred, verified, margin, min_margin=1000):
    """Fail closed; reference lexicon checks permission, not acoustic truth."""
    if not verified or margin < min_margin or pred not in range(len(NAMES)):
        return 'NOOP'
    return NAMES[pred]


def codec(text):
    """27 symbols, A..Z => 0..25, ASCII space => 26; exactly 3 trits."""
    ret = []
    for ch in text.upper():
        if ch == ' ':
            num = 26
        elif 'A' <= ch <= 'Z':
            num = ord(ch) - 65
        else:
            raise ValueError('Base27 input must contain only A-Z and SPACE')
        ret.append([num // 9, (num // 3) % 3, num % 3])
    return ret


def uncodec(trits):
    result = ''
    for item in trits:
        if len(item) != 3 or any(not isinstance(t, int) or t not in (0, 1, 2) for t in item):
            raise ValueError('invalid trits')
        num = 9*item[0] + 3*item[1] + item[2]
        result += ' ' if num == 26 else chr(65 + num)
    return result


def write_header(path, centroids):
    rows = ',\n'.join('  {' + ','.join(map(str, row)) + '}' for row in centroids)
    signatures = ',\n'.join('  {' + ','.join(map(str, row)) + '}' for row in SIG)
    data = ('/* Generated by experiment.py. Synthetic surrogate ONLY. */\n'
            '#ifndef E2E_MODEL_H\n#define E2E_MODEL_H\n'
            '#define E2E_CLASSES 6\n#define E2E_FEATURES 64\n'
            'static const unsigned char CENTROIDS[E2E_CLASSES][64] = {\n'+rows+'\n};\n'
            'static const unsigned char SIGNATURES[E2E_CLASSES][8] = {\n'+signatures+'\n};\n'
            '#endif\n')
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(data, encoding='utf-8')


def run(seed, train_per, test_per, result_dir):
    root = Path(result_dir)
    root.mkdir(parents=True, exist_ok=True)
    train = []
    for label in range(6):
        for profile in range(3):
            for rep in range(train_per):
                train.append((label, features(synth(label, seed+label*100000+profile*10000+rep, profile, 0.08))))
    model = fit(train)
    results = []
    # Strictly disjoint seeds from training; three perturbation profiles.
    for label in range(7):
        for profile in range(3):
            for rep in range(test_per):
                sample_seed = seed + 1000000 + label*100000 + profile*10000 + rep
                wave = synth(label, sample_seed, profile, noise=0.12)
                vec = features(wave)
                predicted, dist, margin = classify(vec, model)
                accepted = gate(predicted, verify(vec, predicted), margin)
                results.append({'truth': NAMES[label] if label < 6 else 'UNKNOWN',
                                'prediction': NAMES[predicted], 'decision': accepted,
                                'profile': profile, 'margin': margin})
    known = [r for r in results if r['truth'] != 'UNKNOWN']
    unknown = [r for r in results if r['truth'] == 'UNKNOWN']
    metrics = {
        'data_type': 'synthetic_multitone_surrogate_not_human_speech',
        'claim_scope': 'software proof of path only, not ASR or hardware benchmark',
        'seed': seed, 'fs_hz': FS, 'pcm_samples': LENGTH,
        'train_samples': len(train), 'test_samples': len(results),
        'known_count': len(known), 'unknown_count': len(unknown),
        'direct_classification_accuracy': round(sum(r['prediction'] == r['truth'] for r in known)/len(known), 6),
        'hybrid_correct_accept_rate': round(sum(r['decision'] == r['truth'] for r in known)/len(known), 6),
        'hybrid_false_accept_unknown_rate': round(sum(r['decision'] != 'NOOP' for r in unknown)/len(unknown), 6),
        'hybrid_reject_known_rate': round(sum(r['decision'] == 'NOOP' for r in known)/len(known), 6),
        'result_is_not_real_audio_accuracy': True,
        'per_profile': {str(p): {
            'n_known': sum(r['profile'] == p for r in known),
            'correct_accept': sum(r['profile'] == p and r['decision'] == r['truth'] for r in known),
        } for p in range(3)}
    }
    (root/'report.json').write_text(json.dumps(metrics, indent=2, ensure_ascii=False)+'\n', encoding='utf-8')
    (root/'predictions.json').write_text(json.dumps(results, indent=2, ensure_ascii=False)+'\n', encoding='utf-8')
    (root/'model.json').write_text(json.dumps({'centroids':model, 'signatures':SIG, 'bins':BINS,
                                            'coeff_q14':COEFF_Q14, 'names':NAMES}, indent=2)+'\n')
    write_header(root.parent/'firmware'/'model.h', model)
    print(json.dumps(metrics, indent=2))
    return metrics


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--seed', type=int, default=20261113)
    ap.add_argument('--train', type=int, default=10)
    ap.add_argument('--test', type=int, default=8)
    ap.add_argument('--results', default=str(Path(__file__).resolve().parent/'results'))
    args = ap.parse_args()
    run(args.seed, args.train, args.test, args.results)